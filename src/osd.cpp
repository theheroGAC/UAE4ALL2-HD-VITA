static SDL_Rect s_dirty_rect[2] = {};
static int s_needs_erase = 0;
static int s_buf_idx = 0;

static void draw_osd_message(SDL_Surface *surface)
{
    if (show_message <= 0 || !show_message_str || show_message_str[0] == '\0') {
        if (s_needs_erase > 0) {
            if (s_dirty_rect[s_buf_idx].w > 0 && s_dirty_rect[s_buf_idx].h > 0) {
                SDL_FillRect(surface, &s_dirty_rect[s_buf_idx], 0);
                s_dirty_rect[s_buf_idx].w = 0;
                s_dirty_rect[s_buf_idx].h = 0;
            }
            s_buf_idx = 1 - s_buf_idx;
            s_needs_erase--;
#if defined(__PSP2__) || defined(__SWITCH__)
            auto_display_needs_clear = 2;
#endif
        }
        return;
    }

    int len = (int)strlen(show_message_str);
    if (len <= 0) {
        show_message = 0;
        return;
    }

    int scale = 1;
    int char_w = 8 * scale;
    int char_h = 8 * scale;
    int pad_x = 5 * scale;
    int pad_y = 2 * scale;

    int text_w = len * char_w;
    int box_w = text_w + pad_x * 2;
    int box_h = char_h + pad_y * 2;

    int active_w = surface->w;
#if defined(__PSP2__) || defined(__SWITCH__)
    if (mainMenu_displayAuto && autoDisplayRect.valid && autoDisplayRect.width > 0) {
        active_w = autoDisplayRect.hires ? (autoDisplayRect.width * 2) : autoDisplayRect.width;
        if (active_w > surface->w)
            active_w = surface->w;
    }
#endif

    if (box_w > active_w - 4) {
        box_w = active_w - 4;
    }
    if (box_w > surface->w - 4) {
        box_w = surface->w - 4;
    }

    int box_x = (active_w - box_w) / 2;
    if (box_x < 2)
        box_x = 2;
    if (box_x + box_w > surface->w - 2)
        box_x = surface->w - box_w - 2;

    int box_y = 4 * scale;
    if (box_y + box_h > surface->h) {
        box_y = surface->h - box_h - 2;
    }
    if (box_y < 0)
        box_y = 0;

    SDL_Rect bg_rect;
    bg_rect.x = (Sint16)box_x;
    bg_rect.y = (Sint16)box_y;
    bg_rect.w = (Uint16)box_w;
    bg_rect.h = (Uint16)box_h;

    SDL_Rect clear_rect;
    clear_rect.x = (Sint16)(box_x > 0 ? box_x - 1 : 0);
    clear_rect.y = (Sint16)(box_y > 0 ? box_y - 1 : 0);
    clear_rect.w = (Uint16)(box_w + 2);
    clear_rect.h = (Uint16)(box_h + 2);
    s_dirty_rect[s_buf_idx] = clear_rect;
    s_dirty_rect[1 - s_buf_idx] = clear_rect;
    s_buf_idx = 1 - s_buf_idx;
    s_needs_erase = 2;

    Uint32 bg_col = SDL_MapRGB(surface->format, 16, 20, 28);
    SDL_FillRect(surface, &bg_rect, bg_col);

    Uint32 border_col = SDL_MapRGB(surface->format, 70, 95, 130);
    SDL_Rect b_top = { (Sint16)box_x, (Sint16)box_y, (Uint16)box_w, 1 };
    SDL_Rect b_bot = { (Sint16)box_x, (Sint16)(box_y + box_h - 1), (Uint16)box_w, 1 };
    SDL_Rect b_lft = { (Sint16)box_x, (Sint16)box_y, 1, (Uint16)box_h };
    SDL_Rect b_rgt = { (Sint16)(box_x + box_w - 1), (Sint16)box_y, 1, (Uint16)box_h };
    SDL_FillRect(surface, &b_top, border_col);
    SDL_FillRect(surface, &b_bot, border_col);
    SDL_FillRect(surface, &b_lft, border_col);
    SDL_FillRect(surface, &b_rgt, border_col);

    Uint32 text_col = SDL_MapRGB(surface->format, 255, 255, 255);
    Uint32 shadow_col = SDL_MapRGB(surface->format, 0, 0, 0);

    int cur_x = box_x + pad_x;
    int cur_y = box_y + pad_y;

    for (int i = 0; i < len; i++) {
        unsigned char c = (unsigned char)show_message_str[i];
        if (c < 32 || c > 126) c = ' ';
        const unsigned char *glyph = s_osd_font_8x8[c - 32];

        for (int r = 0; r < 8; r++) {
            unsigned char row = glyph[r];
            if (!row) continue;
            int col = 0;
            while (col < 8) {
                if (row & (0x80 >> col)) {
                    int run = 0;
                    while ((col + run < 8) && (row & (0x80 >> (col + run)))) {
                        run++;
                    }

                    SDL_Rect s_rect = {
                        (Sint16)(cur_x + col * scale + 1),
                        (Sint16)(cur_y + r * scale + 1),
                        (Uint16)(run * scale),
                        (Uint16)scale
                    };
                    SDL_FillRect(surface, &s_rect, shadow_col);

                    SDL_Rect p_rect = {
                        (Sint16)(cur_x + col * scale),
                        (Sint16)(cur_y + r * scale),
                        (Uint16)(run * scale),
                        (Uint16)scale
                    };
                    SDL_FillRect(surface, &p_rect, text_col);

                    col += run;
                } else {
                    col++;
                }
            }
        }
        cur_x += char_w;
        if (cur_x + char_w > box_x + box_w - pad_x) break;
    }

    show_message--;
}

void OSD_TriggerDiskSwap(int disk_number, bool is_error)
{
    s_osd_disk = disk_number;
    s_osd_error = is_error;
    s_osd_start_ticks = SDL_GetTicks();
    s_osd_visible = true;
}

void OSD_Render(SDL_Surface *surface)
{
    Uint32 elapsed;
    if (!surface) return;
    {
        static int osd_log_count = 0;
        if (osd_log_count < 2) {
            osd_log_count++;
            write_log ("[VITA] OSD_Render: surface=%dx%d bpp=%d visible=%d\n",
                       surface->w, surface->h, surface->format ? (int)surface->format->BitsPerPixel : -1, s_osd_visible ? 1 : 0);
        }
    }
    draw_osd_message(surface);
    if (!s_osd_visible) return;

    elapsed = SDL_GetTicks() - s_osd_start_ticks;
    if (elapsed >= 2500) {
        s_osd_visible = false;
        return;
    }

    int target_x = (900 * surface->w) / 960;
    int target_y = (20 * surface->h) / 544;
    int target_w = (40 * surface->w) / 960;
    int target_h = (40 * surface->h) / 544;

    if (target_w < 6) target_w = 6;
    if (target_h < 6) target_h = 6;

    SDL_Rect dst_rect;
    dst_rect.x = (Sint16)target_x;
    dst_rect.y = (Sint16)target_y;
    dst_rect.w = (Uint16)target_w;
    dst_rect.h = (Uint16)target_h;

    Uint8 r = 0, g = 255, b = 0, a = 200;
    if (s_osd_error) {
        r = 255; g = 0; b = 0;
    } else if (s_osd_disk == 2) {
        r = 255; g = 165; b = 0;
    }

    SDL_Surface *osd_surface = SDL_CreateRGBSurface(
        SDL_SWSURFACE,
        target_w,
        target_h,
        32,
        0x000000FF,
        0x0000FF00,
        0x00FF0000,
        0xFF000000
    );

    if (osd_surface) {
        Uint32 color = SDL_MapRGBA(osd_surface->format, r, g, b, a);
        SDL_FillRect(osd_surface, NULL, color);
        SDL_SetAlpha(osd_surface, SDL_SRCALPHA, a);
        SDL_BlitSurface(osd_surface, NULL, surface, &dst_rect);
        SDL_FreeSurface(osd_surface);
    } else {
        Uint32 fallback_color = SDL_MapRGB(surface->format, r, g, b);
        SDL_FillRect(surface, &dst_rect, fallback_color);
    }
}

